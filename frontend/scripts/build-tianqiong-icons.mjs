// Rebuild the static application icons from the single vector mark.
import { readFile, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"
import path from "node:path"
import { fileURLToPath } from "node:url"

const frontend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const require = createRequire(import.meta.url)
const nextDir = path.dirname(require.resolve("next/package.json"))
const sharp = require(require.resolve("sharp", { paths: [nextDir] }))
const mark = await readFile(path.join(frontend, "public/images/brand/tianqiong-mark.svg"), "utf8")
const match = mark.match(/<svg\b[^>]*>([\s\S]*)<\/svg>/)
if (!match) throw new Error("Invalid Tianqiong SVG mark")
const whiteMark = mark.replaceAll('fill="#000"', 'fill="#fff"')

const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="#10162c"/><g transform="translate(7 7) scale(.78125)">${match[1].replaceAll('fill="#000"', 'fill="#fff"')}</g></svg>`
const source = Buffer.from(icon)
const png = (size) => sharp(source).resize(size, size).png().toBuffer()
const iconPNG = await png(256)
const applePNG = await png(180)
const images = await Promise.all([16, 32, 48, 64, 256].map(async size => ({ size, data: await png(size) })))
const header = Buffer.alloc(6 + images.length * 16)
header.writeUInt16LE(1, 2)
header.writeUInt16LE(images.length, 4)
let offset = header.length
for (const [index, image] of images.entries()) {
  const at = 6 + index * 16
  header[at] = image.size === 256 ? 0 : image.size
  header[at + 1] = image.size === 256 ? 0 : image.size
  header.writeUInt16LE(1, at + 4)
  header.writeUInt16LE(32, at + 6)
  header.writeUInt32LE(image.data.length, at + 8)
  header.writeUInt32LE(offset, at + 12)
  offset += image.data.length
}
await Promise.all([
  writeFile(path.join(frontend, "app/icon.png"), iconPNG),
  writeFile(path.join(frontend, "app/apple-icon.png"), applePNG),
  writeFile(path.join(frontend, "app/favicon.ico"), Buffer.concat([header, ...images.map(image => image.data)])),
  writeFile(path.join(frontend, "components/brand/tianqiong-mark-data.ts"), `// Generated by scripts/build-tianqiong-icons.mjs from the shared SVG.\nexport const TIANQIONG_MARK_DATA_URI = ${JSON.stringify("data:image/svg+xml," + encodeURIComponent(whiteMark))}\n`),
])
console.log("Tianqiong application icons regenerated")
