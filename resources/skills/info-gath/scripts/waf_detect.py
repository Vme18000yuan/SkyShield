#!/usr/bin/env python3
"""
Lightweight WAF / CDN / IPS fingerprinting for reconnaissance.

Checks response headers, status codes, and body signatures against known WAF/CDN patterns.
Does NOT perform intrusive tests.

Usage:
  python waf_detect.py https://example.com
  python waf_detect.py https://example.com --json
"""

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from typing import Any, Dict, List, Tuple
from urllib.parse import urlparse

import requests
try:
    requests.packages.urllib3.disable_warnings()
except Exception:
    pass

# WAF / CDN / IPS signature database
SIGNATURES: List[Tuple[str, str, str, str]] = [
    # (name, header_regex, body_regex, note)
    ("Cloudflare", r"(?i)^cf-ray$|^cf-mitigated$|^server:\s*cloudflare", r"cloudflare", "CDN/WAF"),
    ("Akamai", r"(?i)^x-akamai-transformed$|^server:\s*akamai", r"akamai", "CDN"),
    ("AWS CloudFront", r"(?i)^x-amzn-cf-id$|^via:.*cloudfront", r"cloudfront", "CDN"),
    ("Fastly", r"(?i)^x-fastly", r"fastly", "CDN"),
    ("Sucuri", r"(?i)^x-sucuri", r"sucuri", "WAF"),
    ("Imperva/Incapsula", r"(?i)^x-cdn$|incap_ses|visid_incap", r"incapsula|imperva", "WAF"),
    ("F5 BIG-IP / ASM", r"(?i)^x-waf-status$|^server:\s*bigip", r"the requested url was rejected", "WAF"),
    ("ModSecurity", r"(?i)^mod_security|modsecurity", r"mod_security|this error was generated by mod_security", "WAF"),
    ("Wallarm", r"(?i)^x-wallarm", r"wallarm", "WAF"),
    ("Tencent Cloud WAF", r"(?i)^x-tencent", r"tencent", "WAF"),
    ("Aliyun WAF", r"(?i)^ali-cdn|ali-waf", r"aliyun|alibaba", "WAF/CDN"),
    ("360 Wangzhan", r"(?i)^wzws", r"wangzhan|360", "WAF"),
    ("SafeDog", r"(?i)^safedog", r"safedog", "WAF"),
    ("Yundun", r"(?i)^yundun", r"yundun", "WAF"),
    ("Nginx", r"(?i)^server:\s*nginx", r"", "Reverse Proxy"),
    ("Apache", r"(?i)^server:\s*apache", r"", "Web Server"),
    ("Microsoft IIS", r"(?i)^server:\s*microsoft-iis|^x-aspnet-version", r"", "Web Server"),
    ("Tomcat", r"(?i)^server:\s*tomcat", r"", "App Server"),
]


def fetch(url: str, timeout: float = 8.0) -> Tuple[int, Dict[str, str], str]:
    try:
        resp = requests.get(url, timeout=timeout, verify=False, allow_redirects=True, headers={"User-Agent": "Mozilla/5.0"})
        headers = {k.lower(): v for k, v in resp.headers.items()}
        body = resp.text[:8192]  # limit body scan
        return resp.status_code, headers, body
    except requests.RequestException as e:
        return 0, {}, str(e)


def detect(headers: Dict[str, str], body: str) -> List[Dict[str, str]]:
    findings: List[Dict[str, str]] = []
    header_blob = "\n".join(f"{k}: {v}" for k, v in headers.items())
    combined = header_blob + "\n" + body

    for name, hdr_re, body_re, note in SIGNATURES:
        match = False
        evidence = ""
        if hdr_re and re.search(hdr_re, header_blob, re.IGNORECASE | re.MULTILINE):
            match = True
            evidence = "header"
        if body_re and re.search(body_re, body, re.IGNORECASE):
            match = True
            evidence = evidence + "+body" if evidence else "body"
        if match:
            findings.append({"name": name, "evidence": evidence, "note": note})

    return findings


def main() -> int:
    parser = argparse.ArgumentParser(description="Lightweight WAF/CDN/IPS fingerprint")
    parser.add_argument("url", help="Target URL (e.g. https://example.com)")
    parser.add_argument("--json", action="store_true", help="Output JSON only")
    parser.add_argument("--timeout", type=float, default=8.0)
    args = parser.parse_args()

    url = args.url.strip()
    if not urlparse(url).scheme:
        url = "https://" + url

    status, headers, body = fetch(url, args.timeout)

    if status == 0:
        result = {
            "url": url,
            "error": body,
            "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        }
        print(json.dumps(result, indent=2, ensure_ascii=False))
        return 1

    findings = detect(headers, body)

    result: Dict[str, Any] = {
        "url": url,
        "status": status,
        "headers_sample": {k: headers.get(k, "") for k in ["server", "x-powered-by", "via", "cf-ray", "x-akamai"] if k in headers},
        "detections": findings,
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
    }

    if args.json:
        print(json.dumps(result, indent=2, ensure_ascii=False))
    else:
        print(f"URL: {url}")
        print(f"Status: {status}")
        print("Headers (selected):")
        for k, v in result["headers_sample"].items():
            print(f"  {k}: {v}")
        print("Detections:")
        if findings:
            for f in findings:
                print(f"  [+] {f['name']} ({f['evidence']}) — {f['note']}")
        else:
            print("  [-] No WAF/CDN signatures detected")

    return 0


if __name__ == "__main__":
    sys.exit(main())
