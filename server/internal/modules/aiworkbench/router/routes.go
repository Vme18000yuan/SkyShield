func RegisterAIWorkbenchRoutes(protected *gin.RouterGroup, h *handler.ConversationHandler) {
	protected.GET("/aiChatMentions", h.ChatMentions)
	protected.GET("/aiConversations", h.List)
	protected.POST("/aiConversations", h.Create)
	protected.PATCH("/aiConversations/:conversation", h.UpdateMetadata)
	protected.DELETE("/aiConversations/:conversation", h.Delete)
	protected.POST("/aiConversationDeletions", h.BatchDelete)
	protected.POST("/aiChatAttachments", h.Upload)
	protected.GET("/aiConversations/:conversation/messages", h.Messages)
	protected.GET("/aiConversations/:conversation/messages/:activity", h.MessageDetail)
	for _, path := range []string{"/aiConversations/:conversation/side-questions", "/aiTasks/:task/chat/side-questions", "/aiTasks/:task/mainSessions/:segment/side-questions", "/aiTasks/:task/intents/:intent/side-questions"} {
		protected.GET(path, h.SideQuestions)
		protected.POST(path, h.SideQuestions)
		protected.DELETE(path, h.SideQuestions)
	}
	protected.POST("/aiSideQuestions/:question/cancel", h.CancelSideQuestion)
	protected.GET("/aiSideQuestions/:question/events", h.SideQuestionEvents)
	protected.POST("/aiConversations/:conversation/messages", h.Send)
	protected.GET("/aiConversations/:conversation/activities", h.Activities)
	protected.GET("/aiConversations/:conversation/traffic", h.Traffic)
	protected.GET("/aiConversations/:conversation/traffic/exchange", h.TrafficExchange)
	protected.GET("/aiConversations/:conversation/traffic/blob", h.TrafficBlob)
	protected.POST("/aiConversations/:conversation/stop", h.Stop)
	protected.PUT("/aiConversations/:conversation/model", h.SetProfile)
	protected.GET("/aiToolExecutions", h.ToolExecutions)
	protected.GET("/aiToolExecutions/:execution", h.ToolExecution)
}

